    ADD CONSTRAINT "collected_birds_bird_id_fkey" FOREIGN KEY ("bird_id") REFERENCES "public"."birds"("id") ON DELETE CASCADE;

ALTER TABLE ONLY "public"."collected_birds"
    ADD CONSTRAINT "collected_birds_user_id_fkey" FOREIGN KEY ("user_id") REFERENCES "auth"."users"("id") ON DELETE CASCADE;

ALTER TABLE ONLY "public"."observations"
    ADD CONSTRAINT "observations_user_id_fkey" FOREIGN KEY ("user_id") REFERENCES "auth"."users"("id") ON DELETE CASCADE;

ALTER TABLE ONLY "public"."profiles"
    ADD CONSTRAINT "profiles_id_fkey" FOREIGN KEY ("id") REFERENCES "auth"."users"("id") ON DELETE CASCADE;

ALTER TABLE ONLY "public"."saved_locations"
    ADD CONSTRAINT "saved_locations_user_id_fkey" FOREIGN KEY ("user_id") REFERENCES "auth"."users"("id") ON DELETE CASCADE;

CREATE POLICY "Own collection" ON "public"."collected_birds" USING (("auth"."uid"() = "user_id"));

CREATE POLICY "Own observations" ON "public"."observations" USING (("auth"."uid"() = "user_id"));

CREATE POLICY "Own profile read" ON "public"."profiles" FOR SELECT USING (("auth"."uid"() = "id"));

CREATE POLICY "Own profile update" ON "public"."profiles" FOR UPDATE USING (("auth"."uid"() = "id")) WITH CHECK ((("auth"."uid"() = "id") AND ("role" = ( SELECT "profiles_1"."role"
   FROM "public"."profiles" "profiles_1"
  WHERE ("profiles_1"."id" = "auth"."uid"())))));

CREATE POLICY "Public read access" ON "public"."birds" FOR SELECT USING (true);

CREATE POLICY "Users can manage their own locations" ON "public"."saved_locations" USING (("auth"."uid"() = "user_id")) WITH CHECK (("auth"."uid"() = "user_id"));

