-- Baseline schema captured from dev (rxpafqcecuborfhtskay) for projects created
-- before migration tracking started. Establishes base tables for saved_locations,
-- birds, collected_birds, observations, profiles that later migrations ALTER.

CREATE OR REPLACE FUNCTION "public"."handle_new_user"() RETURNS "trigger"
    LANGUAGE "plpgsql" SECURITY DEFINER
    AS $$
  begin
    insert into public.profiles (id, role) values (new.id, 'user');
    return new;
  end;
  $$;

ALTER FUNCTION "public"."handle_new_user"() OWNER TO "postgres";

SET default_tablespace = '';
SET default_table_access_method = "heap";

CREATE TABLE IF NOT EXISTS "public"."birds" (
    "id" integer NOT NULL,
    "name_eng" "text" NOT NULL,
    "name_latin" "text" NOT NULL,
    "rarity" "text" NOT NULL,
    "biomes" "text"[] DEFAULT '{}'::"text"[] NOT NULL,
    "food" "text"[] DEFAULT '{}'::"text"[] NOT NULL,
    "behaviour" "text"[] DEFAULT '{}'::"text"[] NOT NULL,
    "wingspan" integer NOT NULL,
    "field_note" "text" NOT NULL,
    "image_url" "text",
    "selected_image" "jsonb",
    "best_months" integer[] DEFAULT '{}'::integer[],
    "tips_to_find" "text"[] DEFAULT '{}'::"text"[],
    "field_marks" "text"[] DEFAULT '{}'::"text"[],
    "difficulty" "text" DEFAULT 'easy'::"text",
    "best_time_of_day" "jsonb" DEFAULT '{"day": true, "dawn": false, "dusk": false, "night": false}'::"jsonb",
    "signature_behavior" "text" DEFAULT ''::"text",
    "sound_url" "text",
    "image_public_id" "text",
    "image_resource_type" "text" DEFAULT 'image'::"text",
    "sound_public_id" "text",
    "sound_resource_type" "text" DEFAULT 'video'::"text",
    CONSTRAINT "birds_rarity_check" CHECK (("rarity" = ANY (ARRAY['Common'::"text", 'Uncommon'::"text", 'Rare'::"text", 'Epic'::"text", 'Legendary'::"text"])))
);

ALTER TABLE "public"."birds" OWNER TO "postgres";

ALTER TABLE "public"."birds" ALTER COLUMN "id" ADD GENERATED BY DEFAULT AS IDENTITY (
    SEQUENCE NAME "public"."birds_id_seq"
    START WITH 1
    INCREMENT BY 1
    NO MINVALUE
    NO MAXVALUE
    CACHE 1
);

CREATE TABLE IF NOT EXISTS "public"."collected_birds" (
    "user_id" "uuid" NOT NULL,
    "bird_id" integer NOT NULL,
    "collected_at" timestamp with time zone DEFAULT "now"() NOT NULL
);

ALTER TABLE "public"."collected_birds" OWNER TO "postgres";

CREATE TABLE IF NOT EXISTS "public"."observations" (
    "id" "uuid" DEFAULT "gen_random_uuid"() NOT NULL,
    "user_id" "uuid" NOT NULL,
    "bird_id" integer NOT NULL,
    "observed_at" timestamp with time zone NOT NULL,
    "created_at" timestamp with time zone DEFAULT "now"() NOT NULL,
    "lat" double precision,
    "lng" double precision,
    "seen" boolean DEFAULT false NOT NULL,
    "heard" boolean DEFAULT false NOT NULL,
    "photographed" boolean DEFAULT false NOT NULL,
    "notes" "text",
    "photo_url" "text",
    "location_name" "text",
    "quality" smallint,
    "cloudinary_public_id" "text",
    "cloudinary_resource_type" "text",
    CONSTRAINT "observations_quality_range" CHECK ((("quality" IS NULL) OR (("quality" >= 1) AND ("quality" <= 5))))
);

ALTER TABLE "public"."observations" OWNER TO "postgres";

CREATE TABLE IF NOT EXISTS "public"."profiles" (
    "id" "uuid" NOT NULL,
    "role" "text" DEFAULT 'user'::"text" NOT NULL,
    "created_at" timestamp with time zone DEFAULT "now"() NOT NULL,
    CONSTRAINT "profiles_role_check" CHECK (("role" = ANY (ARRAY['admin'::"text", 'user'::"text"])))
);

ALTER TABLE "public"."profiles" OWNER TO "postgres";

CREATE TABLE IF NOT EXISTS "public"."saved_locations" (
    "id" bigint NOT NULL,
    "user_id" "uuid" NOT NULL,
    "name" "text" NOT NULL,
    "lat" double precision NOT NULL,
    "lng" double precision NOT NULL,
    "created_at" timestamp with time zone DEFAULT "now"() NOT NULL
);

ALTER TABLE "public"."saved_locations" OWNER TO "postgres";

CREATE SEQUENCE IF NOT EXISTS "public"."saved_locations_id_seq"
    START WITH 1
    INCREMENT BY 1
    NO MINVALUE
    NO MAXVALUE
    CACHE 1;

ALTER SEQUENCE "public"."saved_locations_id_seq" OWNER TO "postgres";
ALTER SEQUENCE "public"."saved_locations_id_seq" OWNED BY "public"."saved_locations"."id";
ALTER TABLE ONLY "public"."saved_locations" ALTER COLUMN "id" SET DEFAULT "nextval"('"public"."saved_locations_id_seq"'::"regclass");

ALTER TABLE ONLY "public"."birds"
    ADD CONSTRAINT "birds_pkey" PRIMARY KEY ("id");

ALTER TABLE ONLY "public"."collected_birds"
    ADD CONSTRAINT "collected_birds_pkey" PRIMARY KEY ("user_id", "bird_id");

